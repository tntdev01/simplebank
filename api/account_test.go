func randomAccount() db.Account {
	return db.Account{
		ID:       util.RandomInt(1, 1000),
		Owner:    util.RandomOwner(),
		Balance:  util.RandomBalance(),
		Currency: util.RandomCurrency(),
	}
}

func comparePayload(t *testing.T, body string, account db.Account) {
	require.Contains(t, body, fmt.Sprintf("\"id\":%d", account.ID))
	require.Contains(t, body, fmt.Sprintf("\"owner\":\"%s\"", account.Owner))
	require.Contains(t, body, fmt.Sprintf("\"balance\":%d", account.Balance))
	require.Contains(t, body, fmt.Sprintf("\"currency\":\"%s\"", account.Currency))
}
